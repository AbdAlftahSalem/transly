/// Checks the Dart code against the translations: keys referenced in code
/// that do not exist, wrong placeholder arguments, unused keys and
/// hardcoded user-facing strings.
///
/// All of this is heuristic: the code is scanned with regular expressions
/// over a lexed copy of each file (comments and strings handled), not with
/// the Dart analyzer. It is tuned to never call a key unused when anything
/// in the code could plausibly refer to it.
library;

import 'dart:io';

import 'package:path/path.dart' as p;

import 'config.dart';
import 'dart_scanner.dart';
import 'icu.dart';
import 'issue.dart';
import 'translation_file.dart';
import 'version.dart';

/// A Dart source file to scan.
class DartSource {
  /// Creates a source record.
  DartSource(this.path, this.displayPath, this.content);

  /// The absolute path.
  final String path;

  /// The path shown in reports.
  final String displayPath;

  /// The file content.
  final String content;

  /// The lexed file.
  late final DartScan scan = scanDart(content);
}

final RegExp _generatedHeader = RegExp(r'GENERATED CODE|DO NOT EDIT|Generated file|generated by', caseSensitive: false);

/// Lists the Dart files under [sources] (relative to [root]), skipping
/// generated code (`*.g.dart`, `*.freezed.dart`, gen-l10n output,
/// intl_utils `lib/generated`, files with a "GENERATED CODE" header) and
/// files matching [ignoreGlobs] (`*` and `**` wildcards).
List<DartSource> collectDartSources(String root, List<String> sources,
    {List<String> ignoreGlobs = const [], String? generatedDir}) {
  final out = <DartSource>[];
  final ignore = ignoreGlobs.map(_globToRegExp).toList();
  for (final src in sources) {
    final dir = Directory(p.join(root, src));
    if (!dir.existsSync()) continue;
    final files = dir
        .listSync(recursive: true, followLinks: false)
        .whereType<File>()
        .where((f) => f.path.endsWith('.dart'))
        .toList()
      ..sort((a, b) => a.path.compareTo(b.path));
    for (final f in files) {
      final rel = p.relative(f.path, from: root).replaceAll(r'\', '/');
      final name = p.basename(f.path);
      if (name.endsWith('.g.dart') || name.endsWith('.freezed.dart') || name.endsWith('.gr.dart')) continue;
      if (rel.contains('/generated/') || rel.startsWith('generated/')) continue;
      if (ignore.any((g) => g.hasMatch(rel))) continue;
      final content = f.readAsStringSync();
      final head = content.length > 600 ? content.substring(0, 600) : content;
      if (_generatedHeader.hasMatch(head)) continue;
      if (generatedDir != null && p.isWithin(generatedDir, f.path) && name.startsWith('app_localizations')) continue;
      if (content.contains('abstract class AppLocalizations') || content.contains('class _AppLocalizationsDelegate')) {
        continue;
      }
      out.add(DartSource(f.path, rel, content));
    }
  }
  return out;
}

RegExp _globToRegExp(String glob) {
  final b = StringBuffer('^');
  for (var i = 0; i < glob.length; i++) {
    final c = glob[i];
    if (c == '*') {
      if (i + 1 < glob.length && glob[i + 1] == '*') {
        b.write('.*');
        i++;
        if (i + 1 < glob.length && glob[i + 1] == '/') i++;
      } else {
        b.write('[^/]*');
      }
    } else if (c == '?') {
      b.write('[^/]');
    } else {
      b.write(RegExp.escape(c));
    }
  }
  b.write(r'$');
  return RegExp(b.toString());
}

/// A key reference found in code.
class KeyReference {
  /// Creates a reference.
  const KeyReference(this.key, this.source, this.offset, {this.positionalArgs, this.namedArgs, this.style});

  /// The key as written in code.
  final String key;

  /// The file.
  final DartSource source;

  /// Where the key appears.
  final int offset;

  /// Positional arguments passed (gen-l10n method args or easy_localization
  /// `args: [...]`), or null when none were passed.
  final int? positionalArgs;

  /// easy_localization `namedArgs` keys, or null when none were passed.
  final Set<String>? namedArgs;

  /// `getter` (gen-l10n) or `tr` (easy_localization).
  final String? style;

  /// 1-based line.
  int get line => source.scan.lineOf(offset);
}

/// Members of a gen-l10n class that are not message keys.
const Set<String> _nonKeyMembers = {
  'localeName',
  'delegate',
  'supportedLocales',
  'localizationsDelegates',
  'of',
  'current',
  'load',
  'hashCode',
  'runtimeType',
  'toString',
  'noSuchMethod',
};

/// Options for [checkCode].
class CodeCheckOptions {
  /// Creates options.
  const CodeCheckOptions({
    this.unused = true,
    this.unknown = true,
    this.hardcoded = true,
    this.accessors = const [],
    this.outputClass = 'AppLocalizations',
    this.ignoreKeys = const [],
  });

  /// Report base keys never referenced.
  final bool unused;

  /// Report references to keys that do not exist, and wrong arguments.
  final bool unknown;

  /// Report hardcoded user-facing strings.
  final bool hardcoded;

  /// Extra accessor expressions (`t`, `context.loc`).
  final List<String> accessors;

  /// The gen-l10n class name (`output-class` in l10n.yaml).
  final String outputClass;

  /// Keys skipped everywhere.
  final List<String> ignoreKeys;
}

/// Finds key references in [sources]. For ARB projects this means
/// `AppLocalizations.of(context)!.key`, `context.l10n.key`, `l10n.key`,
/// `S.of(context).key`, `S.current.key` and any configured accessor; for
/// JSON projects `'key'.tr()`, `tr('key')`, `'key'.plural()`,
/// `plural('key')` and `context.tr('key')`.
List<KeyReference> findKeyReferences(List<DartSource> sources, TranslationFormat format,
    {List<String> accessors = const [], String outputClass = 'AppLocalizations'}) {
  final refs = <KeyReference>[];
  if (format == TranslationFormat.arb) {
    final exprs = <String>[
      '${RegExp.escape(outputClass)}\\s*\\.\\s*of\\s*\\(\\s*\\w+\\s*\\)\\s*[!?]?',
      r'\bS\s*\.\s*of\s*\(\s*\w+\s*\)\s*[!?]?',
      r'\bS\s*\.\s*current',
      r'(?<![\w$.])(?:context\s*\.\s*)?l10n\s*[!?]?',
      for (final a in accessors) '(?<![\\w\$.])${a.split('.').map(RegExp.escape).join(r'\s*\.\s*')}\\s*[!?]?',
    ];
    final re = RegExp('(?:${exprs.join('|')})\\s*\\.\\s*([A-Za-z_][A-Za-z0-9_]*)');
    for (final src in sources) {
      final m = src.scan.masked;
      for (final match in re.allMatches(m)) {
        final key = match.group(1)!;
        if (_nonKeyMembers.contains(key)) continue;
        var j = match.end;
        while (j < m.length && ' \t\r\n'.contains(m[j])) {
          j++;
        }
        int? args;
        if (j < m.length && m[j] == '(') {
          final close = matchingBracket(m, j);
          if (close > j) args = splitTopLevel(m.substring(j + 1, close)).length;
        }
        refs.add(KeyReference(key, src, match.end - key.length, positionalArgs: args, style: 'getter'));
      }
    }
  } else {
    final before = RegExp(r'(?:(?<![\w$])|\.\s*)(?:tr|plural|trExists)\s*\(\s*$');
    final after = RegExp(r'^\s*\.\s*(tr|plural)\s*\(');
    for (final src in sources) {
      final m = src.scan.masked;
      for (final s in src.scan.strings) {
        if (s.interpolated) continue;
        final head = m.substring((s.start - 40).clamp(0, s.start), s.start);
        final tail = m.substring(s.end, (s.end + 30).clamp(s.end, m.length));
        int? callOpen;
        if (before.hasMatch(head)) {
          // tr('key', args: [...]) — the call's parenthesis is just before the string.
          callOpen = m.lastIndexOf('(', s.start);
        } else {
          final a = after.firstMatch(tail);
          if (a == null) continue;
          callOpen = s.end + a.end - 1;
        }
        final close = matchingBracket(m, callOpen);
        int? positional;
        Set<String>? named;
        if (close > callOpen) {
          final inner = m.substring(callOpen + 1, close);
          final argsAt = RegExp(r'\bargs\s*:\s*\[').firstMatch(inner);
          if (argsAt != null) {
            final open = callOpen + 1 + argsAt.end - 1;
            final end = matchingBracket(m, open);
            if (end > open) positional = splitTopLevel(m.substring(open + 1, end)).length;
          }
          final namedAt = RegExp(r'\bnamedArgs\s*:\s*\{').firstMatch(inner);
          if (namedAt != null) {
            final open = callOpen + 1 + namedAt.end - 1;
            final end = matchingBracket(m, open);
            if (end > open) {
              named = {};
              for (final lit in src.scan.strings) {
                if (lit.start <= open || lit.end > end) continue;
                final rest = m.substring(lit.end, (lit.end + 4).clamp(lit.end, m.length)).trimLeft();
                if (rest.startsWith(':')) named.add(lit.value);
              }
            }
          }
        }
        refs.add(KeyReference(s.value, src, s.start + 1, positionalArgs: positional, namedArgs: named, style: 'tr'));
      }
    }
  }
  return refs;
}

/// The findings of [checkCode], plus the references found.
class CodeReport {
  /// Creates a report.
  const CodeReport(this.issues, this.references, this.filesScanned);

  /// The findings.
  final List<Issue> issues;

  /// Every key reference found.
  final List<KeyReference> references;

  /// How many Dart files were scanned.
  final int filesScanned;
}

/// Runs the code checks for [base] over [sources].
CodeReport checkCode(TranslationFile base, List<DartSource> sources,
    [CodeCheckOptions options = const CodeCheckOptions()]) {
  final issues = <Issue>[];
  final ignore = KeyMatcher(options.ignoreKeys);
  final refs = findKeyReferences(sources, base.format, accessors: options.accessors, outputClass: options.outputClass);
  final keys = base.entries.keys.toSet();
  final parents = <String>{};
  for (final k in keys) {
    final parts = k.split('.');
    for (var i = 1; i < parts.length; i++) {
      parents.add(parts.take(i).join('.'));
    }
  }
  Issue at(IssueKind kind, KeyReference r, String message) => Issue(kind, message,
      key: r.key, file: r.source.displayPath, line: r.line, column: r.source.scan.columnOf(r.offset));

  if (options.unknown && base.isValid) {
    for (final r in refs) {
      if (ignore.matches(r.key)) continue;
      if (r.source.scan.isIgnored(r.line, ignoreMarker) || r.source.scan.hasComment(ignoreFileMarker)) continue;
      final exists = keys.contains(r.key);
      if (!exists && !parents.contains(r.key)) {
        final hint = _closest(r.key, keys);
        issues.add(at(IssueKind.unknownKey, r,
            '"${r.key}" is not in ${base.fileName}${hint == null ? '' : ' (did you mean "$hint"?)'}'));
        continue;
      }
      if (!exists) continue; // a parent key, e.g. plural('items', n) on items.one/items.other
      final value = base.stringValue(r.key);
      if (value == null) continue;
      final msg = parseIcu(value);
      if (msg.error != null) continue;
      final names = msg.arguments.keys.toList();
      if (r.style == 'getter') {
        final passed = r.positionalArgs ?? 0;
        if (passed != names.length) {
          final want = names.isEmpty ? 'no arguments' : '${names.length} (${names.map((n) => '{$n}').join(', ')})';
          issues.add(at(
              IssueKind.wrongArguments, r, '"${r.key}" takes $want but $passed ${passed == 1 ? 'is' : 'are'} passed'));
        }
      } else {
        final positional = msg.positionalCount;
        final passedPositional = r.positionalArgs ?? 0;
        if (positional != passedPositional) {
          issues
              .add(at(IssueKind.wrongArguments, r, '"${r.key}" has $positional {} but args: passes $passedPositional'));
        }
        final namedInText = names.toSet();
        final passedNamed = r.namedArgs ?? const <String>{};
        final missing = namedInText.difference(passedNamed);
        // A plural's count is passed as the number, not as a named arg.
        missing.removeWhere((n) => msg.arguments[n] == 'plural');
        if (missing.isNotEmpty) {
          issues.add(
              at(IssueKind.wrongArguments, r, '"${r.key}" needs namedArgs ${missing.map((n) => "'$n'").join(', ')}'));
        }
        final extra = passedNamed.difference(namedInText);
        if (extra.isNotEmpty) {
          issues.add(Issue(
              IssueKind.wrongArguments, '"${r.key}" has no {${extra.join('}, {')}} but namedArgs passes it',
              key: r.key, file: r.source.displayPath, line: r.line, severityOverride: Severity.warning));
        }
      }
    }
  }

  if (options.unused && base.isValid && sources.isNotEmpty) {
    final used = usedKeys(base, sources, refs);
    for (final key in base.entries.keys) {
      if (used.contains(key) || ignore.matches(key)) continue;
      issues.add(Issue(IssueKind.unusedKey, 'not referenced in any Dart file',
          locale: base.locale, key: key, file: _display(base, sources), line: base.lineOf(key)));
    }
  }

  if (options.hardcoded) {
    final keySet = keys;
    for (final src in sources) {
      issues.addAll(findHardcodedStrings(src, knownKeys: keySet));
    }
  }
  return CodeReport(issues, refs, sources.length);
}

String? _display(TranslationFile base, List<DartSource> sources) {
  if (sources.isEmpty) return base.path;
  final first = sources.first;
  final root = first.path.substring(0, first.path.length - first.displayPath.length);
  return p.isWithin(root, base.path) ? p.relative(base.path, from: root) : base.path;
}

/// The base keys that [sources] may reference, by any of: an explicit
/// reference, a member access `.key`, a string literal `'key'` (or a parent
/// path of it), the generated `LocaleKeys.key` constant, or a string with
/// interpolation whose static start is a key prefix (`'errors.$code'`).
Set<String> usedKeys(TranslationFile base, List<DartSource> sources, [List<KeyReference>? refs]) {
  final used = <String>{};
  final keys = base.entries.keys.toList();
  final members = <String>{};
  final literals = <String>{};
  final prefixes = <String>{};
  final memberRe = RegExp(r'\.\s*([A-Za-z_][A-Za-z0-9_]*)');
  for (final src in sources) {
    for (final m in memberRe.allMatches(src.scan.masked)) {
      members.add(m.group(1)!);
    }
    for (final s in src.scan.strings) {
      if (s.interpolated) {
        if (s.staticPrefix.length >= 2) prefixes.add(s.staticPrefix);
      } else {
        literals.add(s.value);
      }
    }
  }
  for (final r in refs ?? const <KeyReference>[]) {
    literals.add(r.key);
  }
  for (final key in keys) {
    final underscored = key.replaceAll('.', '_');
    if (members.contains(key) || members.contains(underscored) || literals.contains(key)) {
      used.add(key);
      continue;
    }
    final parts = key.split('.');
    var found = false;
    for (var i = 1; i < parts.length && !found; i++) {
      final parent = parts.take(i).join('.');
      if (literals.contains(parent) || members.contains(parent.replaceAll('.', '_'))) found = true;
    }
    if (!found) found = prefixes.any(key.startsWith);
    if (found) used.add(key);
  }
  return used;
}

/// Widget constructors whose first positional string is shown to the user.
const List<String> textWidgets = ['Text', 'SelectableText', 'AutoSizeText'];

/// Named parameters whose string value is shown to the user.
const List<String> textParameters = [
  'text',
  'title',
  'subtitle',
  'label',
  'labelText',
  'hintText',
  'helperText',
  'errorText',
  'counterText',
  'prefixText',
  'suffixText',
  'tooltip',
  'message',
  'semanticLabel',
  'semanticsLabel',
  'placeholder',
  'content',
  'confirmText',
  'cancelText',
  'helpText',
  'barrierLabel',
];

final RegExp _beforeWidget = RegExp('\\b(?:const\\s+|new\\s+)?(?:${textWidgets.join('|')})(?:\\.rich)?\\s*\\(\\s*\$');
final RegExp _beforeParam = RegExp('(?<![\\w\$])(?:${textParameters.join('|')})\\s*:\\s*\$');
final RegExp _afterLocalized = RegExp(r'^\s*\.\s*(?:tr|plural|i18n|translate)\b');
final RegExp _hasLetter = RegExp(r'\p{L}', unicode: true);
final RegExp _pathLike =
    RegExp(r'^(?:[\w\-]+/)+[\w\-.]+$|^https?://|^[\w\-]+\.(?:png|jpe?g|svg|webp|gif|json|ttf|otf|mp3|mp4|riv|lottie)$');

/// Finds user-facing string literals in [src] that are not localized:
/// the first argument of `Text(...)`, `SelectableText(...)`, `TextSpan(...)`
/// and friends, and values of parameters like `title:`, `hintText:`,
/// `labelText:`, `tooltip:`. Skips strings followed by `.tr()`, strings with
/// no letters, asset paths and URLs, and lines silenced with
/// `// transly:ignore` (same line or the line above).
List<Issue> findHardcodedStrings(DartSource src, {Set<String> knownKeys = const {}}) {
  final scan = src.scan;
  if (scan.hasComment(ignoreFileMarker)) return const [];
  final out = <Issue>[];
  final m = scan.masked;
  for (final s in scan.strings) {
    final text = s.value;
    final visible = text.replaceAll(RegExp(r'\{[^}]*\}'), '');
    if (!_hasLetter.hasMatch(visible)) continue;
    if (_pathLike.hasMatch(text.trim())) continue;
    final head = m.substring((s.start - 60).clamp(0, s.start), s.start);
    if (!_beforeWidget.hasMatch(head) && !_beforeParam.hasMatch(head)) continue;
    final tail = m.substring(s.end, (s.end + 30).clamp(s.end, m.length));
    if (_afterLocalized.hasMatch(tail)) continue;
    if (scan.isIgnored(s.line, ignoreMarker)) continue;
    final shown = text.length > 50 ? '${text.substring(0, 49)}…' : text;
    final looksLikeKey = knownKeys.contains(text);
    out.add(Issue(
      IssueKind.hardcodedString,
      looksLikeKey ? '"$shown" is a translation key used as plain text (missing .tr()?)' : '"$shown" is not localized',
      file: src.displayPath,
      line: s.line,
      column: s.column,
    ));
  }
  return out;
}

String? _closest(String key, Set<String> keys) {
  String? best;
  var bestScore = 1 << 30;
  for (final k in keys) {
    if ((k.length - key.length).abs() > 3) continue;
    final d = _levenshtein(key.toLowerCase(), k.toLowerCase());
    if (d < bestScore) {
      bestScore = d;
      best = k;
    }
  }
  final limit = key.length <= 4 ? 1 : (key.length <= 10 ? 2 : 3);
  return bestScore <= limit ? best : null;
}

int _levenshtein(String a, String b) {
  var prev = List<int>.generate(b.length + 1, (i) => i);
  for (var i = 1; i <= a.length; i++) {
    final cur = List<int>.filled(b.length + 1, 0)..[0] = i;
    for (var j = 1; j <= b.length; j++) {
      final cost = a[i - 1] == b[j - 1] ? 0 : 1;
      cur[j] = [prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + cost].reduce((x, y) => x < y ? x : y);
    }
    prev = cur;
  }
  return prev[b.length];
}
